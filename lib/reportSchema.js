// Shared shape for the structured report data — replaces the old freeform
// markdown blob. Both properties.report_draft_markdown (pre-publish) and
// shared_reports.report_markdown (published) now store JSON.stringify() of
// this shape under those same (historically-named) text columns, rather
// than renaming columns for a schema that's still likely to evolve.
//
// Used by: app/api/report-draft/route.js (generation), app/manage/[id]/review
// (editing), app/report/[token] (customer-facing render).

